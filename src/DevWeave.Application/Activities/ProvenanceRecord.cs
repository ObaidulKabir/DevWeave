using DevWeave.Domain.Activities;

namespace DevWeave.Application.Activities;

/// <summary>
/// A W3C PROV-O projection of one activity: the activity identifier and discriminator (prov:Activity),
/// the responsible actor (prov:Agent), consumed revision-pinned inputs (prov:used) and produced
/// revision-pinned outputs (prov:wasGeneratedBy).
/// </summary>
public sealed record ProvenanceRecord(
    Guid ActivityId,
    string ActivityType,
    Guid Agent,
    IReadOnlyList<ProvenanceRef> Used,
    IReadOnlyList<ProvenanceRef> Generated);

/// <summary>A revision-pinned reference to a knowledge artifact used or generated by an activity.</summary>
public sealed record ProvenanceRef(Guid ItemId, Guid RevisionId);