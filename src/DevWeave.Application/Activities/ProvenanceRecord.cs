using DevWeave.Domain.Activities;

namespace DevWeave.Application.Activities;

/// <summary>
/// A W3C PROV-O projection of one activity: the activity identifier and discriminator (prov:Activity),
/// the responsible actor (prov:Agent), consumed revision-pinned inputs (prov:used), produced
/// revision-pinned outputs (prov:wasGeneratedBy), and optional agent execution metadata (provider/model).
/// </summary>
public sealed record ProvenanceRecord(
    Guid ActivityId,
    string ActivityType,
    Guid Agent,
    IReadOnlyList<ProvenanceRef> Used,
    IReadOnlyList<ProvenanceRef> Generated,
    AgentExecutionProvenance? AgentExecution = null);

/// <summary>A revision-pinned reference to a knowledge artifact used or generated by an activity.</summary>
public sealed record ProvenanceRef(Guid ItemId, Guid RevisionId);

/// <summary>Optional agent-run metadata attached to a Generated activity (AGT-005 / PROV).</summary>
public sealed record AgentExecutionProvenance(
    string Provider,
    string Model,
    string? ModelVersion,
    string? ConfigurationFingerprint,
    string? ToolFingerprint,
    string? ExternalRunReference,
    string? AuthorizationContext);
