using DevWeave.Domain.Activities;

namespace DevWeave.Contracts.Activities.V1;

/// <summary>A revision-pinned input consumed by an activity (SRS PRO-003).</summary>
public sealed record ActivityInputResponse(Guid ItemId, Guid RevisionId, int Position);

/// <summary>A revision-pinned output produced by an activity (SRS PRO-004).</summary>
public sealed record ActivityOutputResponse(Guid ItemId, Guid RevisionId, int Position);

/// <summary>The full append-only provenance record (SRS PRO-001, PRO-002).</summary>
public sealed record ActivityResponse(
    Guid Id,
    Guid TenantId,
    Guid ProjectId,
    ActivityType Type,
    Guid Actor,
    string Purpose,
    ActivityStatus Status,
    DateTimeOffset StartedAt,
    DateTimeOffset? EndedAt,
    string? CorrelationId,
    string? Reason,
    Guid? Reference,
    IReadOnlyList<ActivityInputResponse> Inputs,
    IReadOnlyList<ActivityOutputResponse> Outputs);

/// <summary>The revision a knowledge item had reached at a reconstruction point (SRS REV-007).</summary>
public sealed record ItemVersionSnapshotResponse(Guid ItemId, Guid? RevisionId, int RevisionNumber);

/// <summary>A project's reconstructed state: its timeline plus per-item revision snapshots.</summary>
public sealed record ProjectStateReconstructionResponse(
    IReadOnlyList<ActivityResponse> Activities,
    IReadOnlyList<ItemVersionSnapshotResponse> Items);

/// <summary>A revision-pinned PROV-O reference used or generated by an activity.</summary>
public sealed record ProvenanceRefResponse(Guid ItemId, Guid RevisionId);

/// <summary>A W3C PROV-O projection of one activity (prov:Activity/Agent/used/wasGeneratedBy).</summary>
public sealed record ActivityProvenanceResponse(
    Guid ActivityId,
    string ActivityType,
    Guid Actor,
    IReadOnlyList<ProvenanceRefResponse> Used,
    IReadOnlyList<ProvenanceRefResponse> Generated);

/// <summary>A structured activity error body with a machine-readable code.</summary>
public sealed record ActivityError(string Code, string Message);