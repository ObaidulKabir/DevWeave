using DevWeave.Domain.Identity;
using DevWeave.Domain.Knowledge;
using DevWeave.Domain.Projects;

namespace DevWeave.Domain.Activities;

/// <summary>
/// An append-only provenance record capturing that a human or machine actor did something to a
/// project's knowledge (SRS PRO-001, PRO-002, PRO-005, PRO-008). Activities are immutable once
/// recorded (REV-006): there is no public mutator and the repository exposes no update/delete path,
/// so every activity stands as a permanent audit fact. Inputs and outputs are revision-pinned
/// (PRO-003, PRO-004), linking each consumed/generated artifact to the exact revision involved.
/// </summary>
public sealed class Activity
{
    private readonly List<ActivityInput> _inputs;
    private readonly List<ActivityOutput> _outputs;

    public ActivityId Id { get; }
    public TenantId TenantId { get; }
    public ProjectId ProjectId { get; }
    public ActivityType Type { get; }
    public PrincipalId Actor { get; }
    public string Purpose { get; }
    public ActivityStatus Status { get; }
    public DateTimeOffset StartedAt { get; }
    public DateTimeOffset? EndedAt { get; }
    public string? CorrelationId { get; }
    public string? Reason { get; }

    /// <summary>
    /// The revision this activity acts upon for the REV-008 amendment types (Correction, Retraction,
    /// Supersession). It pins the superseded/corrected/retracted revision rather than a knowledge item
    /// because those amendments are always about one committed version. For all other activity types
    /// this is <see langword="null"/>.
    /// </summary>
    public KnowledgeRevisionId? Reference { get; }

    /// <summary>Revision-pinned inputs consumed by this activity (PRO-003), in stable position order.</summary>
    public IReadOnlyList<ActivityInput> Inputs => _inputs;

    /// <summary>Revision-pinned outputs generated by this activity (PRO-004), in stable position order.</summary>
    public IReadOnlyList<ActivityOutput> Outputs => _outputs;

    private Activity(
        ActivityId id,
        TenantId tenantId,
        ProjectId projectId,
        ActivityType type,
        PrincipalId actor,
        string purpose,
        ActivityStatus status,
        DateTimeOffset startedAt,
        DateTimeOffset? endedAt,
        string? correlationId,
        string? reason,
        KnowledgeRevisionId? reference)
    {
        Id = id;
        TenantId = tenantId;
        ProjectId = projectId;
        Type = type;
        Actor = actor;
        Purpose = purpose;
        Status = status;
        StartedAt = startedAt;
        EndedAt = endedAt;
        CorrelationId = correlationId;
        Reason = reason;
        Reference = reference;
        _inputs = new List<ActivityInput>();
        _outputs = new List<ActivityOutput>();
    }

    public static Activity Create(
        TenantId tenantId,
        ProjectId projectId,
        ActivityType type,
        PrincipalId actor,
        string purpose,
        ActivityStatus status,
        DateTimeOffset startedAt,
        DateTimeOffset? endedAt,
        string? correlationId,
        string? reason,
        KnowledgeRevisionId? reference,
        IReadOnlyList<ActivityInput> inputs,
        IReadOnlyList<ActivityOutput> outputs)
    {
        if (string.IsNullOrWhiteSpace(purpose))
            throw new ArgumentException("Activity purpose is required.", nameof(purpose));

        // REV-008: the amendment types are only meaningful when they both explain the change (Reason)
        // and point at the specific committed revision being amended (Reference).
        if (IsAmendmentType(type)
            && (string.IsNullOrWhiteSpace(reason) || reference is null))
            throw new ArgumentException(
                $"Activity type '{type}' requires both a reason and a referenced revision.",
                nameof(reference));

        var activity = new Activity(
            ActivityId.New(),
            tenantId,
            projectId,
            type,
            actor,
            purpose,
            status,
            startedAt,
            endedAt,
            correlationId,
            reason,
            reference);

        activity._inputs.AddRange(inputs ?? Array.Empty<ActivityInput>());
        activity._outputs.AddRange(outputs ?? Array.Empty<ActivityOutput>());

        return activity;
    }

    private static bool IsAmendmentType(ActivityType type) =>
        type is ActivityType.Correction or ActivityType.Retraction or ActivityType.Supersession;
}